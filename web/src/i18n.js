let locale = detectLocale()

export function getLocale() {
  return locale
}

export function setLocale(nextLocale) {
  locale = nextLocale === 'ja' ? 'ja' : 'en'
  if (typeof document !== 'undefined') document.documentElement.lang = locale
}

export function t(key, variables = {}) {
  const template = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key
  return template.replace(/\{([a-zA-Z0-9_.-]+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`))
}

export function localizeCategory(category) {
  return t(`category.${category}`)
}

export function localizeKind(kind) {
  if (locale !== 'ja') return kind
  return ({ video: '動画', audio: '音声', image: '画像', unknown: '不明' })[kind] || kind
}

function detectLocale() {
  if (typeof navigator === 'undefined') return 'en'
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language]
  return languages.some((language) => String(language || '').toLowerCase().startsWith('ja')) ? 'ja' : 'en'
}
